function innate_trait_reset:initialise()
	self:add_listeners();
end

function innate_trait_reset:add_listeners()
	core:add_listener(
		"CharacterTurnEndInnateTrait",
		"CharacterTurnEnd",
		true,
		function(context)
			local character = context:character();
			local subtype = character:character_subtype_key();

			if self.subtypes[subtype] then
				if character:has_ancillary(self.subtypes[subtype].reset_item) == true then
					self:reroll_innate_trait(character);
                    cm:force_remove_ancillary(character, self.subtypes[subtype].reset_item, false, true);
				end
			end
		end,
		true
	);
end

function innate_trait_reset:reroll_innate_trait(character)
	out("reroll_innate_trait:");
	local character_details = character:character_details();
	local existing_skill = character_details:background_skill();

	if existing_skill ~= "" then
		local char_str = cm:char_lookup_str(character);
		cm:remove_skill_point(char_str, existing_skill, false);
		out("\tremove_skill_point - '"..existing_skill.."'");

		self:apply_new_background_skill(character_details, existing_skill);
	else
		self:apply_new_background_skill(character_details);
	end
end

function innate_trait_reset:apply_new_background_skill(character_details, existing_skill)
	local subtype = character_details:character_subtype_key();
	local new_background_skill = self:get_new_background_skill(subtype, existing_skill);

	if new_background_skill then
		cm:character_details_pick_background_skill(character_details, new_background_skill, false);
		cm:character_details_add_skill_point(character_details, new_background_skill);
		out("apply_new_background_skill - '"..new_background_skill.."'");
		return new_background_skill;
	end
	return "";
end

function innate_trait_reset:get_new_background_skill(subtype, existing_skill)
	local possible_skills = {}; 

	for _, skill in ipairs(self.subtypes[subtype].skills) do
		if existing_skill == nil or skill ~= existing_skill then
			table.insert(possible_skills, skill);
		end
	end

	if #possible_skills > 0 then
		cm:shuffle_table(possible_skills);
		return possible_skills[1];
	end
end